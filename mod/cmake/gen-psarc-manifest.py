#!/usr/bin/env python3
# Fingerprints every psarc in the reference game install and emits the manifest
# the runtime checks mounts against (src/engine/psarc-verify.cpp).
#
# The fingerprint is deliberately cheap: file size + the whole DSAR index
# (header + chunk table) + a few key-derived payload samples. Hashing 111 GB at
# load would be absurd; the index is the tamper-sensitive part (a repack rewrites
# every chunk offset) and the samples catch in-place payload edits. Keep this in
# exact sync with psarc-verify.cpp / psarc-cipher.hpp.
#
#   gen-psarc-manifest.py <game-data-dir|""> <out.inc> <verify_key_hex> <full_hash_max_mb>
import os
import struct
import sys

MASK = (1 << 64) - 1
FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
DSAR_MAGIC = 0x52415344
SAMPLE_COUNT = 8
SAMPLE_BYTES = 64 * 1024


def mix(x):
    x &= MASK
    x = ((x ^ (x >> 30)) * 0xBF58476D1CE4E5B9) & MASK
    x = ((x ^ (x >> 27)) * 0x94D049BB133111EB) & MASK
    return x ^ (x >> 31)


def update(h, data):
    n = len(data) & ~7
    for (word,) in struct.iter_unpack("<Q", memoryview(data)[:n]):
        h = ((h ^ word) * FNV_PRIME) & MASK
    for b in memoryview(data)[n:]:
        h = ((h ^ b) * FNV_PRIME) & MASK
    return h


def update_u64(h, value):
    return update(h, struct.pack("<Q", value & MASK))


def hash_path(text):
    """Byte-wise FNV-1a; mirrors cipher::HashPath. Archives are keyed by this so
    the shipped binary holds no readable list of psarc filenames."""
    h = FNV_OFFSET
    for b in text.encode("utf-8"):
        h = ((h ^ b) * FNV_PRIME) & MASK
    return h


MODE_SIZE_ONLY = 0
MODE_INDEX_SAMPLED = 1
MODE_FULL = 2


def fingerprint(path, key, full_max):
    """(size, hash, mode) -- see the MODE_* constants and psarc-verify.cpp.

    MODE_FULL for archives small enough to hash whole at load (bin.psarc, which
    holds the gameplay dc1 data, is only ~77 MB). MODE_INDEX_SAMPLED for the
    multi-GB ones. MODE_SIZE_ONLY for plain zlib PSAR voice data (speech1/,
    tts1/), which is deliberately not content-hashed but still listed so it stays
    mountable while an unlisted file dropped into the game folder does not.
    """
    size = os.path.getsize(path)

    with open(path, "rb") as f:
        header = f.read(32)
        if len(header) < 32:
            return size, 0, MODE_SIZE_ONLY
        magic, _version, chunk_count, index_size = struct.unpack_from("<IIII", header, 0)
        # Only DSAR archives carry gameplay data worth hashing; plain zlib PSAR
        # (speech1/, tts1/ voice) is size-only by design.
        if magic != DSAR_MAGIC:
            return size, 0, MODE_SIZE_ONLY
        if index_size != 32 + 32 * chunk_count or index_size > size:
            return size, 0, MODE_SIZE_ONLY

        if size <= full_max:
            h = update_u64(FNV_OFFSET, size)
            f.seek(0)
            while True:
                block = f.read(1 << 20)
                if not block:
                    break
                h = update(h, block)
            return size, (h or 1), MODE_FULL

        f.seek(0)
        index = f.read(index_size)
        if len(index) != index_size:
            return size, 0, MODE_SIZE_ONLY

        h = update_u64(FNV_OFFSET, size)
        h = update(h, index)

        if size > index_size + SAMPLE_BYTES:
            span = size - index_size - SAMPLE_BYTES
            for i in range(SAMPLE_COUNT):
                offset = index_size + mix(key ^ ((size + i * 0x9E3779B97F4A7C15) & MASK)) % span
                f.seek(offset)
                sample = f.read(SAMPLE_BYTES)
                if len(sample) != SAMPLE_BYTES:
                    return size, 0, MODE_SIZE_ONLY
                h = update_u64(h, offset)
                h = update(h, sample)
    # 0 doubles as "no fingerprint", so never hand it back as a real one.
    return size, (h or 1), MODE_INDEX_SAMPLED


def main():
    data_dir, out_path, key_hex, full_max_mb = sys.argv[1:5]
    key = int(key_hex, 16) & MASK
    full_max = int(full_max_mb) * 1024 * 1024

    rows = []
    if data_dir and os.path.isdir(data_dir):
        for root, _dirs, files in os.walk(data_dir):
            for name in files:
                if not name.lower().endswith(".psarc"):
                    continue
                full = os.path.join(root, name)
                rel = os.path.relpath(full, data_dir).replace("\\", "/").lower()
                rows.append((rel,) + fingerprint(full, key, full_max))
        rows.sort()

    counts = [sum(1 for r in rows if r[3] == m) for m in (0, 1, 2)]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Generated by cmake/gen-psarc-manifest.py -- do not edit.\n")
        f.write("// Reference install: %s\n" % (data_dir or "(none -- verification disabled)"))
        f.write("// %d archive(s): %d full-hash, %d index+sampled, %d size-only.\n"
                % (len(rows), counts[2], counts[1], counts[0]))
        f.write("// Keyed by cipher::HashPath(relative path); the names below are\n")
        f.write("// comments only, so no psarc filename reaches the binary.\n")
        f.write("constexpr ManifestEntry kGameArchives[] = {\n")
        for rel, size, digest, mode in rows:
            f.write('    { 0x%016Xull, %dull, 0x%016Xull, %d }, // %s\n'
                    % (hash_path(rel), size, digest, mode, rel))
        # Sentinel keeps the array valid C++ even with no reference install.
        f.write("    { 0ull, 0ull, 0ull, 0 },\n")
        f.write("};\n")
        f.write("constexpr size_t kGameArchiveCount = %d;\n" % len(rows))
    print("gen-psarc-manifest: %d archive(s), %d full-hash, %d index+sampled, %d size-only"
          % (len(rows), counts[2], counts[1], counts[0]))


if __name__ == "__main__":
    main()
