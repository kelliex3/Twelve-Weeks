#!/usr/bin/env python3
# Generates full forwarding thunks for the winmm proxy.
#
# NOT part of the build: the three outputs are committed under src/loader/ and
# compiled from there. winmm's export surface only changes with a Windows
# release, so re-run this by hand when that does and commit the result:
#
#   python cmake/gen-winmm-forwarders.py C:/Windows/System32/winmm.dll \n#       src/loader/winmm_thunks.asm src/loader/winmm_exports.def \n#       src/loader/winmm_names.inc
#
# Exporting a hand-picked subset does not work: bink2w64.dll (and the game
# itself) resolve winmm functions with LoadLibrary("winmm.dll") +
# GetProcAddress, which leaves no import-table entry to discover. Any subset is
# therefore a guess, and a wrong guess hands out NULL and breaks startup. So we
# mirror the ENTIRE export surface of the real winmm.
#
# One x64 `jmp` per export forwards any signature without knowing it, which is
# why these have to be assembly: MSVC/clang-cl x64 has no __declspec(naked).
#
#   gen-winmm-forwarders.py <real-winmm.dll> <out.asm> <out.def> <out.inc>
import struct
import sys


def rva_to_off(sections, rva):
    for va, vsz, ptr, rsz in sections:
        if va <= rva < va + max(vsz, rsz):
            return rva - va + ptr
    return None


def read_exports(path):
    data = open(path, "rb").read()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise SystemExit("not a PE file: %s" % path)
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    optsz = struct.unpack_from("<H", data, pe + 20)[0]
    magic = struct.unpack_from("<H", data, pe + 24)[0]
    if magic != 0x20B:
        raise SystemExit("expected PE32+ (x64): %s" % path)
    # DataDirectory[0] = export table, at offset 112 into the 64-bit opt header
    exp_rva, _exp_size = struct.unpack_from("<II", data, pe + 24 + 112)
    sections = []
    for i in range(nsec):
        e = pe + 24 + optsz + i * 40
        vsz, va, rsz, ptr = struct.unpack_from("<IIII", data, e + 8)
        sections.append((va, vsz, ptr, rsz))

    off = rva_to_off(sections, exp_rva)
    if off is None:
        raise SystemExit("no export directory in %s" % path)
    base, nfuncs, nnames = struct.unpack_from("<III", data, off + 16)
    af, an, ao = struct.unpack_from("<III", data, off + 28)
    af_o = rva_to_off(sections, af)
    an_o = rva_to_off(sections, an)
    ao_o = rva_to_off(sections, ao)

    named = []
    for i in range(nnames):
        name_rva = struct.unpack_from("<I", data, an_o + i * 4)[0]
        ordinal = struct.unpack_from("<H", data, ao_o + i * 2)[0] + base
        p = rva_to_off(sections, name_rva)
        end = data.index(b"\0", p)
        named.append((data[p:end].decode("ascii"), ordinal))
    return named, nfuncs, nnames


def main():
    src, out_asm, out_def, out_inc = sys.argv[1:5]
    named, nfuncs, nnames = read_exports(src)
    named.sort(key=lambda x: x[0])

    # An ordinal shared by two names cannot be reproduced in a .def, so fall
    # back to name-only exports rather than emitting something that will not
    # link. Every consumer in this game folder imports by name anyway.
    ordinals = [o for _, o in named]
    use_ordinals = len(set(ordinals)) == len(ordinals)

    with open(out_asm, "w", encoding="ascii") as f:
        f.write("; Generated by cmake/gen-winmm-forwarders.py -- do not edit, committed output.\n")
        f.write("; One jump thunk per real winmm export; the slot is filled at DllMain.\n\n")
        f.write("EXTERN g_to1WinmmFns:QWORD\n\n.code\n\n")
        for i, (name, _o) in enumerate(named):
            f.write("%s PROC\n    jmp QWORD PTR [g_to1WinmmFns + %d]\n%s ENDP\n\n"
                    % (name, i * 8, name))
        f.write("END\n")

    with open(out_def, "w", encoding="ascii") as f:
        f.write("; Generated by cmake/gen-winmm-forwarders.py -- do not edit, committed output.\n")
        f.write("LIBRARY winmm\n")
        f.write("EXPORTS\n")
        for name, o in named:
            f.write("    %s%s\n" % (name, (" @%d" % o) if use_ordinals else ""))

    with open(out_inc, "w", encoding="ascii") as f:
        f.write("// Generated by cmake/gen-winmm-forwarders.py -- do not edit, committed output.\n")
        f.write("// Order must match winmm_thunks.asm exactly.\n")
        f.write("#define TO1_WINMM_COUNT %d\n" % len(named))
        f.write("static const char* const kTo1WinmmNames[TO1_WINMM_COUNT] = {\n")
        for name, _o in named:
            f.write('    "%s",\n' % name)
        f.write("};\n")

    unnamed = nfuncs - nnames
    print("gen-winmm-forwarders: %d named export(s) from %s%s%s"
          % (len(named), src,
             "" if use_ordinals else " (ordinals dropped: duplicates)",
             "" if unnamed <= 0 else " [%d NONAME export(s) cannot be mirrored]" % unnamed))


if __name__ == "__main__":
    main()
