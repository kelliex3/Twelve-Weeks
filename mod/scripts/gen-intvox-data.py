#!/usr/bin/env python3
"""Generate mod/src/net/audio/intvox-data.hpp from tools/features/data/vox_beg.json.

The JSON is the in-tree copy of the authoritative generator's BEG_INT rows
(tools/features/vox_lines.py genbeg, kinds 8..14). Only the interrogation rows
are emitted: the execution rows stay in the guarded exec-beg-data.hpp sink and
the game-derived PCM blob is not needed by the live `say` path.

The record ids, source take crc32s and subtitle crc32s follow vox_lines.py:
kLines = fnv64(record id), kSrc = crc32(speech + prefix), kTxt = crc32(normalised
subtitle text). The subtitle normalisation uses the JSON's composed text (with
the generator's mode decorations removed), which groups the same line across
the voices well enough for the no-repeat history; the game index itself is not
shipped here.
"""
import json
import os
import re
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, "tools", "features", "data", "vox_beg.json")
OUT = os.path.join(ROOT, "mod", "src", "net", "audio", "intvox-data.hpp")
KINDS = list(range(8, 15))


def fnv64(s: str) -> int:
    h = 0xCBF29CE484222325
    for c in s.encode():
        h = ((h ^ c) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def itxt(r: dict) -> str:
    t = r.get("text") or ""
    if " + " in t:
        t = t.rsplit(" + ", 1)[1]
    t = re.sub(r"\s*\(trimmed\)$", "", t)
    t = re.sub(r"\s*\(tail of:.*\)$", "", t)
    t = re.sub(r"\{[^}]*\}", " ", t)
    t = re.sub(r"\s+", " ", t.strip().lower())
    return re.sub(r'[^ -~]|[\\"]', "", t)


def array(name: str, type_: str, values: list) -> list:
    """Wrap a generated C++ array so the header stays reviewable."""
    out = ["    inline constexpr %s %s[] = {" % (type_, name)]
    for i in range(0, len(values), 12):
        out.append("        " + ", ".join(str(v) for v in values[i:i + 12]) + ",")
    out.append("    };")
    return out


def main() -> None:
    recs = [r for r in json.load(open(DATA)) if r["kind"] in KINDS]
    facs, genders, voices = ["scr", "mlt"], "mf", "abcd"  # fac 1 = WLF (mlt)
    rng = {}
    for i, r in enumerate(recs):
        key = (facs.index(r["fac"]), genders.index(r["g"]), voices.index(r["v"]), r["kind"])
        first, count = rng.get(key, (i, 0))
        rng[key] = (first, count + 1)

    o = [
        "#pragma once",
        "",
        "// GENERATED by mod/scripts/gen-intvox-data.py from",
        "// tools/features/data/vox_beg.json (tools/features/vox_lines.py genbeg,",
        "// BEG_INT kinds 8..14). Do not edit by hand: regenerate from the JSON.",
        "//",
        "// The table is in-tree but stays behind TO1_INTVOX_DATA, like the other",
        "// generated-data seams. With the macro off the owner's picks return -1",
        "// and every beat uses the engine's effort events; the pure timeline,",
        "// history and cut rules stay live either way.",
        "",
        '#include "intvox-core.hpp"',
        "",
        "#include <cstdint>",
        "",
        "namespace net::audio::intvox::data {",
        "",
        "#if defined(TO1_INTVOX_DATA)",
        "",
        "    inline constexpr bool kHave = true;",
        "",
    ]
    o += array("kLines", "uint64_t", ["0x%016xULL" % fnv64(r["id"]) for r in recs])
    o += [
        "",
        "    // VXG_RANGE [fac 0 Seraphite / 1 WLF][gender][voice a..d][kind 8..14][2]",
        "    inline constexpr uint16_t kRange[2][2][4][7][2] = {",
    ]
    for f in range(2):
        o.append("        {")
        for g in range(2):
            rows = []
            for v in range(4):
                cells = ["{%d, %d}" % rng.get((f, g, v, k), (0, 0)) for k in KINDS]
                rows.append("{%s}" % ", ".join(cells))
            o.append("            {%s}," % ", ".join(rows))
        o.append("        },")
    o += [
        "    };",
        "",
    ]
    o += array("kDur", "uint16_t", [r["dur"] for r in recs])
    o += [""]
    o += array("kFlag", "uint8_t", [r.get("flag", 0) for r in recs])
    o += [""]
    o += array("kSrc", "uint32_t", [
        zlib.crc32((r["speech"] + (r.get("pre") or "")).encode()) for r in recs])
    o += [""]
    o += array("kTxt", "uint32_t", [zlib.crc32(itxt(r).encode()) for r in recs])
    o += [
        "",
        "    inline constexpr int kCount = %d;" % len(recs),
        "",
        "    inline core::VoxTable Table() noexcept",
        "    {",
        "        return { kLines, &kRange[0][0][0][0][0], kDur, kFlag, kSrc, kTxt, nullptr, kCount };",
        "    }",
        "",
        "#else",
        "",
        "    inline constexpr bool kHave = false;",
        "    inline constexpr int kCount = 0;",
        "    inline core::VoxTable Table() noexcept { return {}; }",
        "",
        "#endif",
        "",
        "} // namespace net::audio::intvox::data",
        "",
    ]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(o))
    print("intvox: %d BEG_INT records -> %s" % (len(recs), OUT))


if __name__ == "__main__":
    main()
