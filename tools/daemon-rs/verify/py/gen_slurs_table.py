#!/usr/bin/env python3
"""Generates src/slurs_table.rs: what slurs.py's `_words` makes of every non-ASCII code point.

  python3 gen_slurs_table.py [PYDIR] > src/slurs_table.rs        (run it with the same CPython as the server: 3.12 = Unicode 15.0)

slurs._words reads a text as NFKD, drops the combining marks, lower-cases, splits on whitespace, strips "!" at the edges of a word and
maps the look-alike letters; everything that is not a-z is dropped at the end. So per code point only these matter: the whitespace
(" "), "!", the letters / digits / symbols of slurs._LOOK, a-z, and "something else" ("?": kept as a placeholder because it stops a "!"
from being an edge character). A code point that decomposes to nothing (a combining mark) maps to "". Code points not listed map to "?".
"""
import os
import sys
import unicodedata

pydir = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/rsverify/daemon/d1/py202")
sys.path.insert(0, pydir)
import slurs

KEEP = set("abcdefghijklmnopqrstuvwxyz!") | {chr(k) if isinstance(k, int) else k for k in slurs._LOOK}
rows = []
for cp in range(0x80, 0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    t = unicodedata.normalize("NFKD", chr(cp))
    t = "".join(ch for ch in t if not unicodedata.combining(ch)).lower()
    out = "".join(" " if ch.isspace() else (ch if ch in KEEP else "?") for ch in t)
    if out != "?":
        rows.append((cp, out))
print("//! Generated by verify/py/gen_slurs_table.py from CPython %s (Unicode %s). Never edit by hand." % (sys.version.split()[0], unicodedata.unidata_version))
print("//! (code point, what slurs._words makes of it); code points that are not listed map to \"?\".")
print("pub static TABLE: &[(u32, &str)] = &[")
for cp, out in rows:
    print("    (0x%X, %s)," % (cp, '"' + out.replace("\\", "\\\\").replace('"', '\\"') + '"'))
print("];")
