class Fake:
    def __init__(self, chunks):
        self.chunks = [bytes.fromhex(c) for c in chunks]

    def recv(self, n):
        if not self.chunks:
            return b""
        c = self.chunks.pop(0)
        if len(c) > n:
            self.chunks.insert(0, c[n:])
            c = c[:n]
        return c


def split(r, b):
    out = []
    i = 0
    while i < len(b):
        k = r.choice([1, 2, 3, 7, 50, 200, 4096, 10 ** 6])
        out.append(b[i:i + k].hex())
        i += k
    if r.random() < 0.1:
        out.insert(r.randint(0, len(out)), "")
    return out


