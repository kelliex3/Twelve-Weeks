def rand_ip(r):
    k = r.random()
    if k < 0.5:
        return r.choice(IPS)
    if k < 0.7:
        return ".".join(str(r.randrange(0, 300)) for _ in range(4))
    pool = ["0", "0", "0", "1", "ff", "abcd", "ABCD", "0001", "00000"]
    parts = [r.choice(pool[:r.choice([4, 9])]) for _ in range(r.randint(2, 9))]
    s = ":".join(parts)
    if r.random() < 0.5:
        i = r.randrange(len(s) + 1)
        s = s[:i] + "::" + s[i:]
    return s


def head(r):
    path = r.choice(["/link", "/link?x=1", "/linkz", "/", "/other", "/link"])
    lines = ["GET %s HTTP/1.1" % path]
    if r.random() < 0.08:
        lines[0] = r.choice(["POST /link HTTP/1.1", "GET", "get /link x", "", "GETé /x", "G'ET \"x\"", "GET  /link", "x" * 100, "PO\x01ST\xad\xa0 /x"])
    hdr = [("Host", "link"), ("Upgrade", r.choice(["websocket", "WebSocket", "h2c", "websocket "])), ("Connection", "Upgrade"),
           ("Sec-WebSocket-Key", r.choice(KEYS)), ("CF-Connecting-IP", rand_ip(r))]
    r.shuffle(hdr)
    for k, v in hdr:
        if r.random() < 0.85:
            lines.append("%s%s%s:%s%s" % (r.choice(["", "", " "]), r.choice([k, k.lower(), k.upper()]), r.choice(["", " "]), r.choice(["", " ", "  "]), v))
    if r.random() < 0.2:
        lines.append(r.choice(["bad line", "X-A: b: c", ":", "A:", "ÀßX: ü"]))
    raw = ("\r\n".join(lines) + "\r\n\r\n").encode("latin-1", "replace")
    if r.random() < 0.3:
        raw += bytes(r.randrange(256) for _ in range(r.randint(0, 40)))
    if r.random() < 0.05:
        raw = raw.replace(b"\r\n\r\n", b"\r\n", 1)
    if r.random() < 0.04:
        raw = b"X" * r.choice([8190, 8192, 8193, 9000]) + raw
    return raw


def frame(r):
    n = r.choice([0, 1, 2, 5, 125, 126, 127, 200, 300, 65535, 65536, 70000, 2 ** 20, 2 ** 20 + 1])
    n = n if n < 80000 or r.random() < 0.5 else r.choice([0, 3, 126])
    masked = r.random() < 0.9
    op = r.choice([0, 1, 2, 8, 9, 10, 2, 2, 15])
    fin = 0x80 if r.random() < 0.8 else 0
    pl = bytes(r.randrange(256) for _ in range(n)) if n < 70000 else b"\0" * n
    mask = bytes(r.randrange(256) for _ in range(4))
    b = bytes([fin | op, (0x80 if masked else 0) | (n if n < 126 else 126 if n < 65536 else 127)])
    if r.random() < 0.05:                     # a length byte that lies about its size field
        b = bytes([fin | op, (0x80 if masked else 0) | r.choice([126, 127])])
    if 126 <= n < 65536:
        b += struct.pack("!H", n)
    elif n >= 65536:
        b += struct.pack("!Q", n)
    if masked:
        b += mask + bytes(x ^ mask[i & 3] for i, x in enumerate(pl))
    else:
        b += pl
    if r.random() < 0.3:
        b += bytes(r.randrange(256) for _ in range(r.randint(1, 6)))
    if r.random() < 0.1:
        b = b[:r.randint(0, len(b))]
    return b


def gen(r, n):
    for _ in range(n):
        x = r.random()
        if x < 0.25:
            yield {"op": "head", "chunks": split(r, head(r))}
        elif x < 0.55:
            b = frame(r)
            k = r.choice([0, 0, 0, 2, 5, 10 ** 6])
            yield {"op": "frame", "pending": b[:k].hex(), "chunks": split(r, b[k:])}
        elif x < 0.65:
            yield {"op": "out", "opcode": r.choice([0, 1, 2, 8, 9, 10]), "payload": bytes(r.randrange(256) for _ in range(r.choice([0, 1, 125, 126, 127, 65535, 65536, 70000]))).hex()}
        elif x < 0.85:
            yield {"op": "ip", "text": rand_ip(r), "hdr": r.choice([None, rand_ip(r), rand_ip(r)]), "peer": r.choice(["127.0.0.1", "10.0.0.1", "::1"])}
        elif x < 0.95:
            yield {"op": "accept", "key": r.choice(KEYS), "ip": rand_ip(r)}
        else:
            yield {"op": "errno", "code": r.choice([1, 4, 9, 12, 13, 22, 24, 32, 90, 98, 99, 100, 101, 103, 104, 105, 107, 108, 110, 111, 113])}


def run():
    import hashlib
    import ipaddress
    import wslink
    for i, c in enumerate(script()):
        op = c["op"]
        r = None
        try:
            if op == "head":
                f = Fake(c["chunks"])
                p, h, rest = wslink.read_request(f)
                r = [p, h, rest.hex(), len(f.chunks)]
            elif op == "frame":
                f = Fake(c["chunks"])
                o, d, fin, pend = wslink.read_frame(f, bytes.fromhex(c["pending"]))
                r = [o, d.hex(), fin, pend.hex(), len(f.chunks)]
            elif op == "out":
                class Sink:
                    def __init__(s):
                        s.b = b""

                    def sendall(s, x):
                        s.b += x
                k = Sink()
                wslink.send_frame(k, c["opcode"], bytes.fromhex(c["payload"]))
                r = k.b.hex()
            elif op == "ip":
                h = {} if c["hdr"] is None else {"cf-connecting-ip": c["hdr"]}
                try:
                    t = str(ipaddress.ip_address(c["text"]))
                except ValueError:
                    t = None
                r = [wslink.client_ip(h, (c["peer"], 1)), t]
            elif op == "accept":
                acc = base64.b64encode(hashlib.sha1(c["key"].encode() + wslink.GUID).digest())
                resp = b"HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Accept: " + acc + b"\r\n\r\n"
                r = [acc.decode(), resp.hex(), (wslink.PROXY_LINE % c["ip"].encode()).hex()]
            elif op == "errno":
                r = str(OSError(c["code"], os.strerror(c["code"])))
        except (ValueError, ConnectionError) as e:
            r = ["ERR", type(e).__name__, str(e)]
        emit(i, r, None)


main(gen, run)
