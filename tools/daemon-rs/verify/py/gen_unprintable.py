#!/usr/bin/env python3
"""Generates src/unprintable.rs: the code point ranges Python's repr() escapes (str.isprintable() is False), above U+007F.

  python3 gen_unprintable.py > src/unprintable.rs        (run it with the same CPython as the server: 3.12 = Unicode 15.0)
"""
import sys
import unicodedata

rows = []
start = None
for cp in range(0x80, 0x110001):
    bad = cp < 0x110000 and not chr(cp).isprintable()
    if bad and start is None:
        start = cp
    elif not bad and start is not None:
        rows.append((start, cp - 1))
        start = None
print("//! Generated by verify/py/gen_unprintable.py from CPython %s (Unicode %s). Never edit by hand." % (sys.version.split()[0], unicodedata.unidata_version))
print("//! Code point ranges (from U+0080) that repr() escapes: str.isprintable() is False.")
print("pub static RANGES: &[(u32, u32)] = &[")
for a, b in rows:
    print("    (0x%X, 0x%X)," % (a, b))
print("];")
