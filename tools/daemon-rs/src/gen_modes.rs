//! tools/modes.json is THE list of FIND MATCH game modes; `load()` is what modeq reads at start-up.
use serde_json::Value;
use std::path::{Path, PathBuf};

/// One row of modes.json.
#[derive(Clone, Debug)]
pub struct ModeEntry {
    pub id: Value,
    pub key: String,
    pub label: String,
}

/// py: gen_modes.py:12 HERE. The directory of the data files next to the Python modules (modes.json,
/// interrogation_lockboxes.json, map_packs.json): `T2R_TOOLS_DIR`, else the directory of the executable.
pub fn tools_dir() -> PathBuf {
    if let Ok(d) = std::env::var("T2R_TOOLS_DIR") {
        if !d.is_empty() {
            return PathBuf::from(d);
        }
    }
    std::env::current_exe().ok().and_then(|p| p.parent().map(|p| p.to_path_buf())).unwrap_or_default()
}

/// py: gen_modes.py:15 load (Err = any failure: missing file, bad JSON, a row without a text "key").
pub fn load_from(dir: &Path) -> Result<Vec<ModeEntry>, ()> {
    let text = std::fs::read(dir.join("modes.json")).map_err(|_| ())?;
    let v: Value = serde_json::from_slice(&text).map_err(|_| ())?;
    let arr = v.as_array().ok_or(())?;
    let mut out = Vec::new();
    for e in arr {
        let key = e.get("key").and_then(|k| k.as_str()).ok_or(())?.to_string();
        let label = e.get("label").and_then(|k| k.as_str()).unwrap_or("").to_string();
        out.push(ModeEntry { id: e.get("id").cloned().unwrap_or(Value::Null), key, label });
    }
    Ok(out)
}

pub fn load() -> Result<Vec<ModeEntry>, ()> {
    load_from(&tools_dir())
}

/// py: gen_modes.py:19 header (the generated tools/ext/modes.h text).
pub fn header_from(dir: &Path) -> Result<String, ()> {
    let m = load_from(dir)?;
    for (i, e) in m.iter().enumerate() {
        if e.id.as_i64() != Some(i as i64) {
            return Err(());
        }
    }
    let mut out = vec![
        "// GENERATED by tools/gen_modes.py from tools/modes.json - do not edit".to_string(),
        format!("#define MODE_N {}", m.len()),
        "static const struct { const char *key, *label; } MODE_TAB[MODE_N] = {".to_string(),
    ];
    for e in &m {
        out.push(format!("    {{\"{}\", \"{}\"}},", e.key, e.label));
    }
    out.push("};".to_string());
    Ok(out.join("\n") + "\n")
}
